// aurora-local-patch: constellation-build-data
// The constellation data that ships with the viewer
// (assets/constellations/, the patch set's data folder) as a table of
// `include_bytes!` in OUT_DIR, which world/constellations_builtin.rs
// includes: the executable carries it, and nothing is read from disk to
// show it. A module of build.rs's `main` (`#[path]`).
//
// Every regular file of the folder is listed, sorted by its path inside
// it; dot files are left out (the patch tool's record among them). No
// folder: an empty table, and the viewer shows only the user's data. The
// file is written only when its text changes, so a build without changes
// stays fresh; the folder is watched whole when it exists, else its parent
// (a missing path would rerun this script on every build).

use std::path::Path;

/// Writes `$OUT_DIR/constellations_builtin.rs`.
pub fn constellation_data() {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("Cargo supplies CARGO_MANIFEST_DIR");
    let assets = Path::new(&manifest).join("assets");
    let source = assets.join("constellations");
    println!(
        "cargo:rerun-if-changed={}",
        Path::new(&manifest).join("build_constellations.rs").display()
    );
    let mut files: Vec<(String, std::path::PathBuf)> = Vec::new();
    if source.is_dir() {
        println!("cargo:rerun-if-changed={}", source.display());
        constellation_files(&source, "", &mut files);
    } else {
        println!("cargo:rerun-if-changed={}", assets.display());
    }
    files.sort();
    let mut text = String::from(
        "// Generated by build.rs (build_constellations.rs): the constellation data built in.\n\
         pub static FILES: &[(&str, &[u8])] = &[\n",
    );
    for (rel, path) in &files {
        let path = path.to_str().expect("the data folder's path is UTF-8");
        text.push_str(&format!("    ({rel:?}, include_bytes!({path:?})),\n"));
    }
    text.push_str("];\n");
    let out = Path::new(&std::env::var("OUT_DIR").expect("Cargo supplies OUT_DIR")).join("constellations_builtin.rs");
    if std::fs::read_to_string(&out).ok().as_deref() != Some(text.as_str()) {
        std::fs::write(&out, text).expect("the build folder is writable");
    }
}

/// The regular files under `dir` (`prefix`: its path inside the data
/// folder), dot files and folders left out.
fn constellation_files(dir: &Path, prefix: &str, out: &mut Vec<(String, std::path::PathBuf)>) {
    let entries = std::fs::read_dir(dir).expect("the constellation data folder is readable");
    for entry in entries.flatten() {
        let name = entry.file_name().to_str().expect("the data's file names are UTF-8").to_owned();
        if name.starts_with('.') {
            continue;
        }
        let rel = if prefix.is_empty() { name } else { format!("{prefix}/{name}") };
        let path = entry.path();
        if path.is_dir() {
            constellation_files(&path, &rel, out);
        } else if path.is_file() {
            out.push((rel, path));
        }
    }
}
